import type { Alert, AnalystNote } from '@/types';

// Deterministic local "AI analyst" — rule-based reasoning engine.
// This is NOT a real LLM call. It is a functional local demo mode that
// generates plain-English explanations distinguishing observed facts
// from hypotheses and clearly stating uncertainty.
// A real deployment would replace `analyzeAlert` with a call to a
// server-side endpoint that forwards to a model API.

export interface AnalysisSection {
  heading: string;
  kind: 'fact' | 'hypothesis' | 'action';
  confidence: 'observed' | 'likely' | 'possible' | 'low';
  body: string;
}

export interface AnalysisResult {
  summary: string;
  sections: AnalysisSection[];
  uncertainty: string;
  suggestedActions: string[];
  disclaimer: string;
}

const DISCLAIMER =
  'This analysis is generated by a local rule-based reasoning engine (DEMO MODE), not a live AI model. ' +
  'Statements marked "observed" are directly supported by event evidence. ' +
  'Statements marked "likely" or "possible" are inferences and should be verified against source-system logs before action.';

export function analyzeAlert(alert: Alert): AnalysisResult {
  const sections: AnalysisSection[] = [];
  const suggestedActions: string[] = [];

  const evCount = alert.findings.reduce((n, f) => n + f.evidence.length, 0);
  const firstTs = alert.findings
    .flatMap((f) => f.evidence)
    .map((e) => e.timestamp)
    .sort()[0];
  const lastTs = alert.findings
    .flatMap((f) => f.evidence)
    .map((e) => e.timestamp)
    .sort()
    .reverse()[0];
  const ips = Array.from(new Set(alert.findings.flatMap((f) => f.evidence.map((e) => e.sourceIp))));
  const users = Array.from(
    new Set(alert.findings.flatMap((f) => f.evidence.map((e) => e.username ?? '')).filter(Boolean)),
  );
  const types = Array.from(new Set(alert.findings.flatMap((f) => f.evidence.map((e) => e.type))));

  // FACTS — observed directly from events
  sections.push({
    heading: 'Observed evidence',
    kind: 'fact',
    confidence: 'observed',
    body: `${alert.title} is supported by ${evCount} event(s) recorded between ${firstTs} and ${lastTs}. ` +
      `Event types observed: ${types.join(', ')}. ` +
      `Source IPs involved: ${ips.join(', ') || 'none'}. ` +
      `Accounts involved: ${users.join(', ') || 'none'}.`,
  });

  for (const f of alert.findings) {
    sections.push({
      heading: `Detection: ${f.ruleName}`,
      kind: 'fact',
      confidence: 'observed',
      body: f.description,
    });
  }

  // HYPOTHESES — inferences, marked with confidence
  const hasBruteForce = alert.findings.some((f) => f.ruleType === 'brute_force');
  const hasFailedLogins = alert.findings.some((f) => f.ruleType === 'failed_logins');
  const hasLoginBurst = alert.findings.some((f) => f.ruleType === 'login_burst');
  const hasSuccessAfterFailure = alert.findings
    .flatMap((f) => f.evidence)
    .some((e) => e.type === 'login_success')
    && alert.findings.flatMap((f) => f.evidence).some((e) => e.type === 'login_failed');

  if (hasBruteForce) {
    sections.push({
      heading: 'Credential attack interpretation',
      kind: 'hypothesis',
      confidence: 'likely',
      body:
        'The volume and cadence of failed logins from a single source against a single account is consistent with an automated credential attack. ' +
        'This is inferred from the event pattern, not from a confirmed attacker identity.',
    });
  }
  if (hasSuccessAfterFailure) {
    sections.push({
      heading: 'Possible successful compromise',
      kind: 'hypothesis',
      confidence: 'possible',
      body:
        'A successful login follows a large number of failed attempts for the same account. This MAY indicate that the attacker eventually guessed valid credentials, ' +
        'but it is also consistent with the legitimate user logging in after the attack. Verify by checking MFA usage, user agent, and whether the user reported difficulty.',
    });
    suggestedActions.push('Verify whether the successful login used MFA and matches the user\'s normal device and user agent.');
  }
  if (hasLoginBurst) {
    sections.push({
      heading: 'Session token reuse interpretation',
      kind: 'hypothesis',
      confidence: 'possible',
      body:
        'Rapid successful logins for one user from many distinct IPs may indicate stolen session tokens or a credential leak. ' +
        'It may also reflect legitimate use of multiple corporate devices or a VPN roaming event. Correlate with device management logs before concluding compromise.',
    });
    suggestedActions.push('Revoke active sessions for the affected user and force re-authentication.');
  }
  if (ips.some((ip) => ip.startsWith('45.') || ip.startsWith('185.') || ip.startsWith('91.'))) {
    sections.push({
      heading: 'External / suspicious origin',
      kind: 'hypothesis',
      confidence: 'likely',
      body:
        'At least one source IP falls outside known corporate ranges and is associated with public relay infrastructure, increasing the likelihood that traffic is external.',
    });
  }

  // ACTIONS — defensive recommendations (conservative; never auto-execute)
  suggestedActions.push('Confirm the observations against the source system (auth server / endpoint logs) before any irreversible action.');
  suggestedActions.push('If the pattern persists, block the source IP at the perimeter firewall and alert the account owner.');
  suggestedActions.push('Document findings as analyst notes so the investigation trail is preserved.');

  const sevLabel = alert.severity.toUpperCase();
  const summary =
    `${sevLabel} alert "${alert.title}" is supported by ${evCount} observed events. ` +
    `${alert.findings.length} detection rule(s) fired. ` +
    `The analysis below separates confirmed observations from inferences; verify inferences before acting.`;

  // Uncertainty statement — be honest about what the data cannot prove
  const unknowns: string[] = [];
  if (users.length === 0) unknowns.push('no authenticated user is named in the evidence');
  if (ips.length > 1) unknowns.push('the relationship between multiple source IPs is not established by these events alone');
  unknowns.push('the events are synthetic DEMO DATA and do not reflect real network telemetry');
  const uncertainty =
    'This engine cannot determine true intent. ' +
    (unknowns.length > 0 ? 'Limitations: ' + unknowns.join('; ') + '. ' : '') +
    'Treat all hypotheses as leads to verify, not conclusions.';

  return {
    summary,
    sections,
    uncertainty,
    suggestedActions: Array.from(new Set(suggestedActions)),
    disclaimer: DISCLAIMER,
  };
}

export function noteKindFromSection(kind: AnalysisSection['kind']): AnalystNote['kind'] {
  if (kind === 'fact') return 'observation';
  if (kind === 'hypothesis') return 'hypothesis';
  return 'action';
}
